/** Known product terms are localized. Unknown terms remain distinguishable as readable words. */
export function productTerm(value: string, text: Translate) {
  const key = value.replace(/[\s_.:/-]/g, '').toLowerCase()
  if (labels[key]) return text(...labels[key])
  const readable = value.replace(/([a-z\d])([A-Z])/g, '$1 $2').replace(/[_.]+/g, ' ').trim()
  return readable ? readable.charAt(0).toUpperCase() + readable.slice(1) : text('未记录', 'Not recorded')
}

export function skillName(value: string, text: Translate) {
  return productTerm(value.replace(/^skill:/, '').replace(/@\d+$/, '').split('.').at(-1) ?? value, text)
}
