from __future__ import annotations

from pathlib import Path
from typing import Any

README_STATUS_BEGIN = "<!-- BEGIN GENERATED M1 STATUS -->"
README_STATUS_END = "<!-- END GENERATED M1 STATUS -->"


def display_number(value: object, *, unit: str | None = None) -> str:
    if value is None:
        return "not_evaluated"
    if isinstance(value, float):
        rendered = f"{value:.6g}"
    else:
        rendered = str(value)
    return f"{rendered} {unit}" if unit else rendered


def display_ratio(value: object) -> str:
    if not isinstance(value, (int, float)):
        return "not_evaluated"
    return f"{value * 100:.1f}%"


def display_duration(value: object) -> str:
    if not isinstance(value, (int, float)):
        return "not_evaluated"
    if value < 1:
        return f"{value * 1000:.1f} ms"
    if value < 60:
        return f"{value:.2f} s"
    if value < 3600:
        return f"{value / 60:.2f} min"
    return f"{value / 3600:.2f} h"


def _timing_line(label: str, payload: object) -> str | None:
    if not isinstance(payload, dict) or not payload.get("count"):
        return None
    return (
        f"- {label}: p50={display_duration(payload.get('p50_seconds'))}, "
        f"p95={display_duration(payload.get('p95_seconds'))}, "
        f"max={display_duration(payload.get('max_seconds'))}"
    )


def _diagnostic_counts(result: dict[str, Any]) -> tuple[str, list[dict[str, Any]]]:
    diagnostics = result.get("monitoring_diagnostics")
    if not isinstance(diagnostics, dict):
        raw = int(result["raw_latency_candidate_count"])
        excluded = int(result["excluded_nonsteady_count"])
        return (
            f"raw={raw}, steady_state={max(raw - excluded, 0)}, "
            f"excluded={excluded}, exclusions=[legacy_result]",
            [],
        )
    exclusions = diagnostics.get("exclusion_counts")
    exclusion_text = "none"
    if isinstance(exclusions, dict) and exclusions:
        exclusion_text = ", ".join(
            f"{key}={value}" for key, value in sorted(exclusions.items())
        )
    summary = (
        f"raw={diagnostics.get('raw_candidate_count', 0)}, "
        f"steady_state={diagnostics.get('eligible_count', 0)}, "
        f"excluded={diagnostics.get('excluded_count', 0)}, "
        f"exclusions=[{exclusion_text}]"
    )
    examples = diagnostics.get("excluded_examples")
    return (
        summary,
        [item for item in examples if isinstance(item, dict)]
        if isinstance(examples, list)
        else [],
    )


def render_m1_status_markdown(result: dict[str, Any]) -> str:
    latency = result["latency"]
    if not isinstance(latency, dict):
        raise TypeError("M1 result latency payload must be an object")
    delivery = result["source_delivery_coverage"]
    if isinstance(delivery, dict):
        delivery_status = (
            f"{delivery.get('accepted_expected_items', 0)}/{delivery.get('expected_items', 0)} "
            f"= {display_ratio(delivery.get('coverage'))}; "
            f"missed={delivery.get('missed_items', 0)}, "
            f"unexpected={delivery.get('unexpected_items', 0)}"
        )
    else:
        delivery_state = result.get("source_delivery_status")
        deadline = result.get("delivery_deadline")
        provisional = result.get("source_delivery_provisional")
        if delivery_state == "awaiting_delivery_grace" and isinstance(provisional, dict):
            delivery_status = (
                "not_evaluated "
                f"(awaiting_delivery_grace; provisional="
                f"{provisional.get('accepted_expected_items', 0)}/"
                f"{provisional.get('expected_items', 0)}; deadline={deadline})"
            )
        else:
            delivery_status = "not_evaluated"
    diagnostic_summary, excluded_examples = _diagnostic_counts(result)
    lines = [
        "<!-- GENERATED by M1 benchmark tooling; DO NOT EDIT BY HAND. -->",
        "### Current benchmark evidence",
        "",
        f"- Benchmark run: `{result['benchmark_run_id']}`",
        f"- Deployment: `{result['deployment_revision_id']}`",
        f"- Suite: `{result['suite_ref']}`",
        f"- Window: `{result['window_start']}` → `{result['window_end']}`",
        f"- Source taxonomy: {display_number(result['source_category_count'])} categories",
        f"- Latency candidates: {diagnostic_summary}, evaluable={latency['evaluable_samples']}",
        f"- Evaluable coverage: {display_ratio(latency['evaluable_coverage'])}",
        f"- p50: {display_duration(latency['p50_seconds'])}",
        f"- p95: {display_duration(latency['p95_seconds'])}",
        f"- max: {display_duration(latency['max_seconds'])}",
        f"- Within 6h: {display_ratio(latency['within_6h_rate'])}",
        f"- Source delivery coverage: {delivery_status}",
        f"- Latency sample digest: `{result['latency_sample_digest']}`",
    ]
    manifest_id = result.get("expected_event_manifest_id")
    manifest_digest = result.get("expected_event_manifest_digest")
    provider_snapshot_ref = result.get("provider_snapshot_ref")
    if isinstance(manifest_id, str) and manifest_id:
        lines.append(f"- Expected-event manifest: `{manifest_id}`")
    if isinstance(manifest_digest, str) and manifest_digest:
        lines.append(f"- Expected-event manifest digest: `{manifest_digest}`")
    if isinstance(provider_snapshot_ref, str) and provider_snapshot_ref:
        lines.append(f"- Provider snapshot: `{provider_snapshot_ref}`")
    diagnostics = result.get("monitoring_diagnostics")
    if isinstance(diagnostics, dict):
        timing = diagnostics.get("eligible_timing")
        if isinstance(timing, dict):
            timing_lines = [
                line
                for line in (
                    _timing_line("Provider/discovery", timing.get("provider_discovery_seconds")),
                    _timing_line("Queue/dispatch", timing.get("queue_dispatch_seconds")),
                    _timing_line("Ingestion/commit", timing.get("ingestion_commit_seconds")),
                )
                if line is not None
            ]
            if timing_lines:
                lines.extend(["", "#### Eligible latency decomposition", "", *timing_lines])
    if excluded_examples:
        lines.extend(
            [
                "",
                "#### Excluded-candidate diagnostics",
                "",
                (
                    "| Source | Object | Reason | Event→commit | Event→observed | "
                    "Queue | Observed→commit |"
                ),
                "| --- | --- | --- | ---: | ---: | ---: | ---: |",
            ]
        )
        for item in excluded_examples:
            lines.append(
                "| "
                + " | ".join(
                    [
                        f"`{item.get('source_id', 'unknown')}`",
                        f"`{item.get('external_object_id', 'unknown')}`",
                        f"`{item.get('exclusion_reason', 'unknown')}`",
                        display_duration(item.get("end_to_end_seconds")),
                        display_duration(item.get("provider_discovery_seconds")),
                        display_duration(item.get("queue_dispatch_seconds")),
                        display_duration(item.get("ingestion_commit_seconds")),
                    ]
                )
                + " |"
            )
    return "\n".join(lines) + "\n"


def project_m1_readme_status(
    text: str,
    status_markdown: str,
    *,
    label: str = "README",
) -> str:
    if text.count(README_STATUS_BEGIN) != 1 or text.count(README_STATUS_END) != 1:
        raise ValueError(
            f"{label} must contain exactly one generated M1 status marker pair"
        )
    begin = text.index(README_STATUS_BEGIN) + len(README_STATUS_BEGIN)
    end = text.index(README_STATUS_END)
    if begin >= end:
        raise ValueError(f"invalid generated M1 status marker order in {label}")
    replacement = f"\n\n{status_markdown.rstrip()}\n\n"
    return text[:begin] + replacement + text[end:]


def update_m1_readme_status(path: Path, status_markdown: str) -> None:
    text = path.read_text(encoding="utf-8")
    path.write_text(
        project_m1_readme_status(text, status_markdown, label=str(path)),
        encoding="utf-8",
    )
